def _quat2axisangle(quat):
    """Convert quaternion to axis-angle (robosuite convention).

    Matches robosuite.utils.transform_utils.quat2axisangle which expects
    (x, y, z, w) order. LIBERO env outputs robot0_eef_quat in this order.
    Training data state[3:6] was generated by this exact function.
    """
    import math
    quat = np.asarray(quat, dtype=np.float64)
    # clip quaternion w component
    w = np.clip(quat[3], -1.0, 1.0)
    den = np.sqrt(1.0 - w * w)
    if math.isclose(den, 0.0):
        return np.zeros(3)
    return (quat[:3] * 2.0 * math.acos(w)) / den


def resize_image(image, size):
    """Resize image to target size."""
    import PIL.Image
    img = PIL.Image.fromarray(image)
    img = img.resize((size, size), PIL.Image.Resampling.BILINEAR)
    return np.array(img)


def get_libero_env(task, resolution, seed, perturbed_condition=None):
    """Initialize LIBERO environment (optionally under a perturbed condition)."""
    task_description = task.language
    task_bddl_file = pathlib.Path(get_libero_path("bddl_files")) / task.problem_folder / task.bddl_file
    if perturbed_condition is not None:
        from mlvla.data_gen.generate import TASKS, PERTURBED_ROOT, build_env_bddl
        import yaml
        conds = yaml.safe_load((PERTURBED_ROOT / "conditions.yaml").read_text())["conditions"]
        condition = conds[perturbed_condition]
        stem = dict((desc, stem) for stem, desc in TASKS)[task_description]
        task_bddl_file = build_env_bddl(condition, stem)
        logging.info(f"Perturbed env bddl: {task_bddl_file}")
    env_args = {"bddl_file_name": task_bddl_file, "camera_heights": resolution, "camera_widths": resolution}
    env = OffScreenRenderEnv(**env_args)
    env.seed(seed)
    return env, task_description


def _make_eval_config(checkpoint_type, task_name):
    """Recreate the exact model/data architecture used by each trainer."""
    if checkpoint_type == "wizard":
        return tre.get_train_config(
            task_name=task_name,
            output_dir=pathlib.Path("/tmp/wizard_eval_unused"),
            num_steps=1,
            phase=1,
            batch_size=1,
            base_checkpoint=_paths.get("base_checkpoint"),
        )

    base = _config.get_config("pi0_libero_low_mem_finetune")
    # Must be the trainer's WizardPi05Config, not a vanilla Pi0Config: the
    # patched model carries rank-16 lora on every site (vanilla gemma_300m_lora
    # is rank 32) and lm_head lora sites, so canonical npz injection reshapes
    # exactly. A vanilla model silently mismatches ranks and lacks lm_head.
    model_config = tre.get_model_config()
    return dataclasses.replace(
        base,
        name="pi05_libero_lora_goal_expert_eval",
        model=model_config,
        data=tre.get_data_config(_paths.get("base_checkpoint")),
        freeze_filter=model_config.get_freeze_filter(),
        weight_loader=weight_loaders.CheckpointWeightLoader(
            _paths.get("base_checkpoint") + "/params"
        ),
        batch_size=1,
        num_workers=0,
        ema_decay=None,
    )


def load_model(checkpoint_type, params_dir, task_name, canonical_adapter=None):
    """Load pi05 base plus the checkpoint, rejecting partial/mismatched restores."""
    train_config = _make_eval_config(checkpoint_type, task_name)

    init_rng = jax.random.PRNGKey(42)

    # Create mesh with correct axis name for inference
    mesh = sharding.make_mesh(num_fsdp_devices=1)

    # Wizard checkpoints intentionally contain LoRA tensors only.  Loading the
    # pretrained base first is therefore mandatory; a random fresh base makes
    # every downstream metric meaningless.
    train_state, _ = tre.init_train_state(train_config, init_rng, mesh, skip_base_weight_load=False)

    if canonical_adapter is not None:
        from mlvla.adapters.canonical_lora import CanonicalLoRAAdapter
        from mlvla.adapters.table8_converter import inject_table8_adapter
        model = nnx.merge(train_state.model_def, train_state.params)
        adapter = CanonicalLoRAAdapter.load_npz(canonical_adapter)
        adapter.validate()
        inject_table8_adapter(model, adapter)
        logging.info("Injected canonical adapter from %s", canonical_adapter)
        return model, train_config, mesh

    params_path = pathlib.Path(params_dir)
    logging.info(f"Loading {checkpoint_type} checkpoint from {params_path}...")

    loaded_params = _load_checkpoint_fast(params_path, checkpoint_type, restore_type=jnp.ndarray)
    if isinstance(loaded_params, dict):
        loaded_count = len(traverse_util.flatten_dict(loaded_params))
    else:
        loaded_count = len(loaded_params.flat_state())
    train_state, overlay_count, shape_mismatches = _overlay_params(train_state, loaded_params)
    if overlay_count != loaded_count or shape_mismatches:
        raise RuntimeError(
            "Checkpoint/model architecture mismatch: "
            f"restored={overlay_count}/{loaded_count}, shape_mismatches={shape_mismatches}. "
            "Refusing to evaluate a partially restored policy."
        )
    logging.info("Strict restore succeeded: %d/%d tensors", overlay_count, loaded_count)

    model = nnx.merge(train_state.model_def, train_state.params)

    return model, train_config, mesh


def create_policy(model, train_config, sampling_num_steps):
    """Build the same transform chain used by OpenPI training/inference."""
    from openpi.policies import policy as _policy
    from openpi.training import checkpoints as _checkpoints
    import openpi.transforms as transforms

    data_config = train_config.data.create(train_config.assets_dirs, train_config.model)
    norm_stats = _checkpoints.load_norm_stats(
        pathlib.Path(_paths.get("base_checkpoint")) / "assets",
        data_config.asset_id,
    )
    if norm_stats is None:
        raise RuntimeError("LIBERO norm_stats were not found; refusing unnormalized evaluation")
    logging.info(
        "Policy normalization: asset_id=%s use_quantiles=%s",
        data_config.asset_id,
        data_config.use_quantile_norm,
    )
    return _policy.Policy(
        model,
        transforms=[
            transforms.InjectDefaultPrompt(None),
            *data_config.data_transforms.inputs,
            transforms.Normalize(norm_stats, use_quantiles=data_config.use_quantile_norm),
            *data_config.model_transforms.inputs,
        ],
        output_transforms=[
            *data_config.model_transforms.outputs,
            transforms.Unnormalize(norm_stats, use_quantiles=data_config.use_quantile_norm),
            *data_config.data_transforms.outputs,
        ],
        sample_kwargs={"num_steps": sampling_num_steps},
        metadata=train_config.policy_metadata,
    )


def run_episode(env, policy, task_description, args, episode_idx, initial_state=None):
    """Run a single episode."""
    # Reseed env per trial so each trial gets a different initial state
    env.seed(args.seed + episode_idx)
    obs = env.reset()
    if initial_state is not None:
        obs = env.set_init_state(initial_state)
    action_plan = collections.deque()

    t = 0
    max_steps = args.max_steps + args.num_steps_wait
    import time
    t0 = time.time()

    while t < max_steps:
        try:
            if t < args.num_steps_wait:
                obs, reward, done, info = env.step(LIBERO_DUMMY_ACTION)
                t += 1
                continue

            if not action_plan:
                img = resize_image(np.ascontiguousarray(obs["agentview_image"][::-1, ::-1]), args.resize_size)
                wrist = resize_image(
                    np.ascontiguousarray(obs["robot0_eye_in_hand_image"][::-1, ::-1]), args.resize_size
                )
                result = policy.infer({
                    "observation/image": img.astype(np.uint8),
                    "observation/wrist_image": wrist.astype(np.uint8),
                    "observation/state": np.concatenate([
                        obs["robot0_eef_pos"],
                        _quat2axisangle(obs["robot0_eef_quat"]),
                        obs["robot0_gripper_qpos"],
                    ]).astype(np.float32),
                    "prompt": str(task_description),
                })
                # Policy.infer applies Normalize before sampling and Unnormalize
                # plus LiberoOutputs afterwards.
                action_plan.extend(np.asarray(result["actions"])[:args.replan_steps])

            # Execute action
            action_to_execute = action_plan.popleft()
            obs, reward, done, info = env.step(action_to_execute)
            t += 1

            # Progress logging every 50 steps
            if t % 50 == 0:
                elapsed = time.time() - t0
                logging.info(f"  Trial {episode_idx+1}: step {t}/{max_steps} ({elapsed:.0f}s elapsed)")

            if done:
                success = reward > 0.9
                return success, t, reward

        except Exception as e:
            logging.error(f"Error at step {t}: {e}")
            import traceback
            traceback.print_exc()
            return False, t, 0.0

    return False, t, 0.0


def main(argv=None):
    parser = argparse.ArgumentParser()
    parser.add_argument("--task", type=str, default="put the bowl on top of the cabinet")
    parser.add_argument("--checkpoint_type", choices=["wizard", "openpi"], required=True)
    parser.add_argument("--params_dir", type=str, default=None)
    parser.add_argument("--canonical_adapter", type=str, default=None,
                        help="canonical LoRA npz to inject (alternative to --params_dir)")
    parser.add_argument("--num_trials", type=int, default=20)
    parser.add_argument("--seed", type=int, default=7)
    parser.add_argument("--replan_steps", type=int, default=5)
    parser.add_argument("--num_steps_wait", type=int, default=10)
    parser.add_argument("--resize_size", type=int, default=224)
    parser.add_argument("--sampling_num_steps", type=int, default=10)
    parser.add_argument("--max_steps", type=int, default=200)
    parser.add_argument("--perturbed_condition", type=str, default=None,
                        help="Perturbed condition id (e.g. v1_azimuth30); builds the env "
                             "from the same perturbed bddl/scene used for data generation")
    parser.add_argument("--output", type=pathlib.Path, default=None)
    args = parser.parse_args(argv)

    if bool(args.params_dir) == bool(args.canonical_adapter):
        parser.error("exactly one of --params_dir or --canonical_adapter is required")

    logging.info(f"Starting closed-loop evaluation")
    logging.info(f"Checkpoint type: {args.checkpoint_type}")
    logging.info(f"Task: {args.task}")
    logging.info(f"Num trials: {args.num_trials}")

    # Find task. LIBERO-plus's libero_goal benchmark only lists perturbed
    # task variants, so resolve the original task via the generator's TASKS
    # table (bddl/init files are identical across the two checkouts).
    import types

    from mlvla.data_gen.generate import INIT_DIR, TASKS

    stem = dict((desc, s) for s, desc in TASKS).get(args.task)
    if stem is None:
        logging.error(f"Task '{args.task}' not found in TASKS")
        return
    task = types.SimpleNamespace(
        language=args.task, problem_folder="libero_goal", bddl_file=stem + ".bddl"
    )
    import torch

    initial_states = torch.load(
        str(INIT_DIR / (stem + ".pruned_init")), map_location="cpu", weights_only=False
    )

    model, train_config, mesh = load_model(args.checkpoint_type, args.params_dir, args.task,
                                            canonical_adapter=args.canonical_adapter)
    policy = create_policy(model, train_config, args.sampling_num_steps)

    # Create environment
    env, task_description = get_libero_env(task, LIBERO_ENV_RESOLUTION, args.seed,
                                            perturbed_condition=args.perturbed_condition)

    # Run trials with mesh context
    successes = []

    with sharding.set_mesh(mesh):
        for trial_idx in range(args.num_trials):
            logging.info(f"Trial {trial_idx + 1}/{args.num_trials} starting...")
            success, steps, reward = run_episode(
                env,
                policy,
                task_description,
                args,
                trial_idx,
                initial_state=initial_states[trial_idx % len(initial_states)],
            )
            successes.append(success)
            logging.info(f"Trial {trial_idx + 1}: success={success}, steps={steps}, reward={reward:.3f}")

    success_rate = np.mean(successes)
    logging.info(f"\n{'='*60}")
    logging.info(f"Success rate: {success_rate:.2%} ({np.sum(successes)}/{args.num_trials})")
    logging.info(f"{'='*60}")

    if args.output is not None:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(json.dumps({
            "success_rate": float(success_rate),
            "num_success": int(np.sum(successes)),
            "num_trials": args.num_trials,
            "task": args.task,
            "checkpoint_type": args.checkpoint_type,
            "checkpoint": args.params_dir,
            "canonical_adapter": args.canonical_adapter,
            "perturbed_condition": args.perturbed_condition,
            "per_trial_success": successes,
        }, indent=2) + "\n")
        logging.info(f"Results saved to {args.output}")


if __name__ == "__main__":
    main()
